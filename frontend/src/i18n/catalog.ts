export function translate(text: string, language: Language) {
  if (language === "en") return text;
  const trimmed = text.trim();
  let result = roman[trimmed];
  if (!result) {
    const rules: [RegExp, (...args: string[]) => string][] = [
      [
        /^Your child’s school day and learning story at (.+)\.$/,
        (name) => `${name} mein aap ke bachay ki hazri aur parhai ka jaiza.`,
      ],
      [/^(\d+) pending$/, (n) => `${n} kaam baqi`],
      [/^(\d+) unread messages?$/, (n) => `${n} paighamat abhi nahi parhay`],
      [/^Consent recorded (.+)$/, (date) => `Ijazat record hui: ${date}`],
      [/^Hello, (.+)\.$/, (name) => `Assalam-o-Alaikum, ${name}.`],
    ];
    for (const [pattern, format] of rules) {
      const m = trimmed.match(pattern);
      if (m) {
        result = format(...m.slice(1));
        break;
      }
    }
  }
  return result ? text.replace(trimmed, result) : text;
}
